DROP TABLE monitora;
DROP TABLE Participa;
DROP TABLE Alocado;
DROP TABLE Inscricao;
DROP TABLE Atividades;
DROP TABLE Turmas;
DROP TABLE Instrutores;
DROP TABLE Cursos;
DROP TABLE Pagamentos;
DROP TABLE Alunos;
DROP TABLE Telefones;
DROP TABLE Enderecos;

CREATE TABLE Enderecos(
	id INTEGER GENERATED BY DEFAULT AS IDENTITY, -- auto incremento
	rua VARCHAR(50) NOT NULL,
	bairro VARCHAR(50) NOT NULL,
	cep CHAR(8) NOT NULL,
	cidade VARCHAR(50) NOT NULL,
	estado CHAR(2) NOT NULL,						-- adicionado

	CONSTRAINT pk_endereco PRIMARY KEY (id)
);

CREATE TABLE Telefones(
	id INTEGER GENERATED BY DEFAULT AS IDENTITY, -- auto incremento
	telefone_1 VARCHAR(11) NOT NULL,
	telefone_2 VARCHAR(11),

	CONSTRAINT pk_telefone PRIMARY KEY (id)
);

CREATE TABLE Alunos(
	CPF CHAR(11),
	matricula CHAR(8),
	sexo CHAR(1),
	nome VARCHAR(50) NOT NULL,
	email VARCHAR(100) NOT NULL,
	data_de_nacimento DATE NOT NULL,
	fk_telefone INTEGER NOT NULL,
	fk_endereco INTEGER NOT NULL,

	CONSTRAINT pf_aluno PRIMARY KEY (CPF, matricula),
	CONSTRAINT check_sexo CHECK(sexo IN ('M', 'F', 'N')),
	CONSTRAINT fk_aluno_telefone FOREIGN KEY (fk_telefone)
		REFERENCES Telefones(id),
	CONSTRAINT fk_aluno_endereco FOREIGN KEY (fk_endereco)
		REFERENCES  Enderecos(id)
);

CREATE TABLE Pagamentos(
	id INTEGER GENERATED BY DEFAULT AS IDENTITY,
	forma_de_pagamento varchar(20) NOT NULL,
	status varchar(20) NOT NULL,
	data_de_criacao TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
	data_de_venciemento TIMESTAMP NOT NULL,
	data_de_pagamento TIMESTAMP,
	fk_aluno_matricula CHAR(8) NOT NULL,
	fk_aluno_CPF CHAR(11) NOT NULL,

	CONSTRAINT pk_pagamento PRIMARY KEY (id),

	CONSTRAINT check_data_de_vencimento CHECK(data_de_venciemento > data_de_criacao),

	CONSTRAINT check_forma_de_pagamento CHECK(forma_de_pagamento IN ('pix', 'debito', 'credito')),

	CONSTRAINT check_status CHECK (status IN ('pendente', 'processando', 'pago', 'vencido')),

	CONSTRAINT fk_pagamento_aluno
	    FOREIGN KEY (fk_aluno_CPF, fk_aluno_matricula)
	    REFERENCES Alunos(CPF, matricula)
);

CREATE TABLE Cursos(
	id INTEGER GENERATED BY DEFAULT AS IDENTITY,
	nome VARCHAR(50) NOT NULL,
	ementa BLOB SUB_TYPE TEXT NOT NULL,
	descricao BLOB SUB_TYPE TEXT NOT NULL,

	CONSTRAINT pk_cursos PRIMARY KEY (id)
);

CREATE TABLE Instrutores(
	CPF CHAR(11),
	matricula CHAR(10),
	nome VARCHAR(50) NOT NULL,
	email varchar(100) NOT NULL UNIQUE,
	fk_telefone INTEGER NOT NULL UNIQUE,

	CONSTRAINT pk_instrutores PRIMARY KEY (CPF, matricula),
	CONSTRAINT fk_instrutores_telefone FOREIGN KEY (fk_telefone)
		REFERENCES Telefones(id)

);

CREATE TABLE Turmas(
	id INTEGER GENERATED BY DEFAULT AS IDENTITY,
	data_de_inicio DATE NOT NULL,
	vagas_maximas INTEGER NOT NULL,
	carga_horaria DECIMAL NOT NULL,
	turno char(5) NOT NULL,
	fk_curso INTEGER NOT NULL,

	CONSTRAINT pk_Turmas PRIMARY KEY (id),
	CONSTRAINT check_turno CHECK(turno IN ('manha', 'tarde', 'noite')),
	CONSTRAINT check_carga_horaria CHECK(carga_horaria > 0),
	CONSTRAINT fk_turma_curso FOREIGN KEY (fk_curso)
		REFERENCES Cursos(id)
);

CREATE TABLE Atividades(
	id INTEGER GENERATED BY DEFAULT AS IDENTITY,
	data_da_atividade TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
	descricao BLOB SUB_TYPE TEXT NOT NULL,
	carga_horaria DECIMAL NOT NULL,
	fk_turma INTEGER NOT NULL,

	CONSTRAINT pk_atividades PRIMARY KEY (id),
	CONSTRAINT fk_atividade_turma FOREIGN KEY (fk_turma)
		REFERENCES Turmas(id)
);

CREATE TABLE Inscricao(
	fk_curso INTEGER NOT NULL,
	fk_aluno_matricula CHAR(8) NOT NULL,
	fk_aluno_CPF CHAR(11) NOT NULL,
	valor DECIMAL NOT NULL,

	CONSTRAINT pk_inscricao
		PRIMARY KEY
		(fk_curso, fk_aluno_matricula, fk_aluno_CPF),
	CONSTRAINT fk_inscricao_curso
		FOREIGN KEY (fk_curso)
		REFERENCES Cursos(id),
	CONSTRAINT fk_inscricao_aluno
		FOREIGN KEY (fk_aluno_CPF ,fk_aluno_matricula)
		REFERENCES Alunos(CPF,matricula),
	CONSTRAINT check_valor CHECK(valor > 0)
);

CREATE TABLE Alocado (
	fk_turma INTEGER NOT NULL,
	fk_aluno_matricula CHAR(8) NOT NULL,
	fk_aluno_CPF CHAR(11) NOT NULL,

	CONSTRAINT pk_alocado
		PRIMARY KEY
		(fk_turma, fk_aluno_matricula, fk_aluno_CPF),

	CONSTRAINT fk_alocado_turma
		FOREIGN KEY (fk_turma)
		REFERENCES Turmas(id),

	CONSTRAINT fk_alocado_aluno
		FOREIGN KEY (fk_aluno_CPF ,fk_aluno_matricula)
		REFERENCES Alunos(CPF,matricula)
);

CREATE TABLE Participa(
	fk_aluno_matricula CHAR(8) NOT NULL,
	fk_aluno_CPF CHAR(11) NOT NULL,
	fk_atividade INTEGER NOT NULL,
	frequencia BOOLEAN DEFAULT FALSE NOT NULL,
	nota DECIMAL,

	CONSTRAINT pk_participa PRIMARY KEY (fk_atividade, fk_aluno_matricula, fk_aluno_CPF),

	CONSTRAINT fk_participa_aluno
		FOREIGN KEY (fk_aluno_CPF ,fk_aluno_matricula)
		REFERENCES Alunos(CPF,matricula),

	CONSTRAINT fk_participa_atividade
		FOREIGN KEY (fk_atividade)
		REFERENCES Atividades(id),

	CONSTRAINT check_nota CHECK (nota > 0)
);

CREATE TABLE monitora(
    fk_turmas INTEGER NOT NULL,
    fk_instrutores_CPF CHAR(11) NOT NULL ,
    fk_instrutores_matricula CHAR(10) NOT NULL,

    CONSTRAINT pk_monitora
    	PRIMARY KEY
    	(fk_turmas, fk_instrutores_CPF, fk_instrutores_matricula),

    CONSTRAINT fk_monitora_turma
    	FOREIGN KEY (fk_turmas)
    	REFERENCES Turmas(id),

    CONSTRAINT fk_monitora_instrutor
    	FOREIGN KEY (fk_instrutores_CPF, fk_instrutores_matricula)
    	REFERENCES Instrutores(CPF, matricula)
);
